def parse_preset(data):
    """Разбирает массив пресета на регистры"""
    registers = {}
    i = 0
    pa_table_start = None
    
    while i < len(data) - 1:
        addr = data[i]
        value = data[i + 1]
        
        # Маркер конца регистров
        if addr == 0x00 and value == 0x00:
            pa_table_start = i + 2
            break
        
        registers[addr] = value
        i += 2
    
    # PA таблица (последние 8 байт)
    pa_table = data[pa_table_start:pa_table_start + 8] if pa_table_start else []
    
    return registers, pa_table

def print_preset(name, registers, pa_table):
    """Выводит информацию о пресете"""
    print(f"\n{'='*60}")
    print(f"Пресет: {name}")
    print(f"{'='*60}")
    
    # Сортируем регистры по адресу
    for addr in sorted(registers.keys()):
        reg_name = REGISTERS.get(addr, f"REG_0x{addr:02X}")
        value = registers[addr]
        print(f"  0x{addr:02X} ({reg_name:12}): 0x{value:02X} ({value:3} dec)")
    
    if pa_table:
        print(f"\n  PA Table: {' '.join([f'0x{v:02X}' for v in pa_table])}")

def compare_presets():
    """Сравнивает все пресеты и находит различия"""
    parsed = {}
    
    # Парсим все пресеты
    for name, data in PRESETS.items():
        registers, pa_table = parse_preset(data)
        parsed[name] = {'registers': registers, 'pa_table': pa_table}
        print_preset(name, registers, pa_table)
    
    # Находим различия
    print(f"\n{'='*60}")
    print("СРАВНЕНИЕ ПРЕСЕТОВ")
    print(f"{'='*60}")
    
    all_registers = set()
    for preset_data in parsed.values():
        all_registers.update(preset_data['registers'].keys())
    
    # Сравниваем каждый регистр во всех пресетах
    differences = {}
    for reg_addr in sorted(all_registers):
        values = {}
        for name, preset_data in parsed.items():
            if reg_addr in preset_data['registers']:
                values[name] = preset_data['registers'][reg_addr]
        
        # Если значения разные
        if len(set(values.values())) > 1:
            differences[reg_addr] = values
    
    if differences:
        print("\nНайдены различия в регистрах:")
        for reg_addr in sorted(differences.keys()):
            reg_name = REGISTERS.get(reg_addr, f"REG_0x{reg_addr:02X}")
            print(f"\n  0x{reg_addr:02X} ({reg_name}):")
            for name, value in differences[reg_addr].items():
                print(f"    {name:15}: 0x{value:02X}")
    else:
        print("\nВсе пресеты имеют одинаковые значения регистров (кроме тех, что должны отличаться)")

if __name__ == "__main__":
    compare_presets()

